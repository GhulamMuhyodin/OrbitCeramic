<?php

declare(strict_types=1);

/**
 * Write config/config.php from environment variables (CI / deploy).
 *
 * Required env:
 *   ORBIT_DB_HOST, ORBIT_DB_NAME, ORBIT_DB_USER, ORBIT_DB_PASS
 *
 * Optional:
 *   ORBIT_DB_PORT (default 3306)
 *   ORBIT_DEFAULT_SITE_ID (default site-orbit)
 *   ORBIT_TIMEZONE (default Asia/Karachi)
 *   ORBIT_API_KEY
 *   ORBIT_PUBLIC_BASE_URL
 *   ORBIT_CORS_ORIGINS (comma-separated)
 *   ORBIT_ADMIN_SESSION_HOURS (default 8)
 */

$root = dirname(__DIR__);
$out = $root . '/config/config.php';

$host = getenv('ORBIT_DB_HOST') ?: '';
$name = getenv('ORBIT_DB_NAME') ?: '';
$user = getenv('ORBIT_DB_USER') ?: '';
$pass = getenv('ORBIT_DB_PASS');
if ($pass === false) {
    $pass = '';
}

if ($host === '' || $name === '' || $user === '') {
    fwrite(STDERR, "Missing ORBIT_DB_HOST / ORBIT_DB_NAME / ORBIT_DB_USER\n");
    exit(1);
}

$port = (int) (getenv('ORBIT_DB_PORT') ?: 3306);
$siteId = getenv('ORBIT_DEFAULT_SITE_ID') ?: 'site-orbit';
$timezone = getenv('ORBIT_TIMEZONE') ?: 'Asia/Karachi';
$apiKey = getenv('ORBIT_API_KEY') ?: '';
$publicBase = rtrim((string) (getenv('ORBIT_PUBLIC_BASE_URL') ?: ''), '/');
$sessionHours = max(1, (int) (getenv('ORBIT_ADMIN_SESSION_HOURS') ?: 8));

$corsRaw = getenv('ORBIT_CORS_ORIGINS') ?: '';
$cors = array_values(array_filter(array_map('trim', explode(',', $corsRaw))));
if ($cors === []) {
    $cors = ['*'];
}

$export = static function (mixed $value): string {
    return var_export($value, true);
};

$config = <<<PHP
<?php

/**
 * Generated by bin/ci-write-config.php — do not commit.
 * Deploy / CI only.
 */
return [
    'db' => [
        'host' => {$export($host)},
        'port' => {$port},
        'name' => {$export($name)},
        'user' => {$export($user)},
        'pass' => {$export($pass)},
        'charset' => 'utf8mb4',
    ],
    'default_site_id' => {$export($siteId)},
    'timezone' => {$export($timezone)},
    'cors_origins' => {$export($cors)},
    'api_key' => {$export($apiKey)},
    'admin_session_hours' => {$sessionHours},
    'public_base_url' => {$export($publicBase)},
    'uploads_dir' => __DIR__ . '/../public/uploads',
    'uploads_url_path' => '/uploads',
    'max_upload_bytes' => 20 * 1024 * 1024,
];

PHP;

if (!is_dir(dirname($out))) {
    mkdir(dirname($out), 0755, true);
}

if (file_put_contents($out, $config) === false) {
    fwrite(STDERR, "Could not write {$out}\n");
    exit(1);
}

echo "Wrote {$out}\n";
